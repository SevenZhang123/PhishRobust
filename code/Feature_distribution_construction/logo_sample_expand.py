# For each brand, the brand's logo list (official logo, positively enhanced logo) is expanded based on
# traditional CV data augmentation methods to facilitate the next step
# of building a more reasonable feature distribution model.

import os
import random
import math
import numpy as np
from PIL import Image, ImageOps, ImageFilter
from tqdm import tqdm
from torchvision import transforms
from torchvision.transforms import functional as TF


# ==========================================
# 1. Configuration Parameters
# ==========================================
class Config:
    data_root = '../../data/target_list_134/target_list'
    save_root = '../../data/target_list_134/target_list_134_augmented'

    # The total number of benign enhancements expected to be generated by each brand
    target_benign_count = 100

    brand_list = []
    f_brand = open("../../data/target_list_134/target_dict", "r")
    for line in f_brand:
        brand_list.append(line.split("\t")[0])


# ==========================================
# 2. Utility Functions
# ==========================================
def square_pad_resize(img, size=224):
    """
    Basic preprocessing:
    1. Maintain aspect ratio and fill the white border to a square.
    2. Scale to the specified size (224x224)
    """
    w, h = img.size
    max_side = max(w, h)
    padding = ((max_side - w) // 2, (max_side - h) // 2, (max_side - w + 1) // 2, (max_side - h + 1) // 2)
    img = ImageOps.expand(img, padding, fill=(255, 255, 255))
    img = img.resize((size, size), Image.BILINEAR)
    return img


# ==========================================
# 3. Benign Enhancement Method
# ==========================================
def apply_random_benign_aug(img_pil):
    """
    Strategy:
    1. Randomly select one method from the method pool (to avoid image corruption caused by overlapping methods).
    2. Randomly generate the parameters of this method within a reasonable range.
    """
    # Define the option pool for enhancement methods
    methods = ['rotate', 'color', 'affine', 'perspective', 'blur']

    # 1. Randomly select one method
    choice = random.choice(methods)

    # 2. Randomly determine parameters and execute
    if choice == 'rotate':
        # Randomly rotate -30 to 30 degrees
        angle = random.uniform(-30, 30)
        return TF.rotate(img_pil, angle, fill=[255, 255, 255])

    elif choice == 'color':
        # Randomly adjust brightness, contrast, saturation, and hue.
        brightness = random.uniform(0.6, 1.4)
        contrast = random.uniform(0.6, 1.4)
        saturation = random.uniform(0.6, 1.4)
        hue = random.uniform(-0.05, 0.05)

        img = TF.adjust_brightness(img_pil, brightness)
        img = TF.adjust_contrast(img, contrast)
        img = TF.adjust_saturation(img, saturation)
        img = TF.adjust_hue(img, hue)
        return img

    elif choice == 'affine':
        # Affine transformation (translation + scaling + shearing only, rotation is handled by rotate)
        angle = 0
        translate = (random.uniform(0, 0.1), random.uniform(0, 0.1))  # 平移幅度 10%
        scale = random.uniform(0.9, 1.1)
        shear = random.uniform(-10, 10)
        return TF.affine(img_pil, angle, translate, scale, shear, fill=[255, 255, 255])

    elif choice == 'perspective':
        # Perspective transformation (simulating side-view effect)
        distortion_scale = random.uniform(0, 0.4)
        transformer = transforms.RandomPerspective(distortion_scale=distortion_scale, p=1.0)
        return transformer(img_pil)

    elif choice == 'blur':
        # Gaussian blur (simulates out-of-focus/low resolution)
        radius = random.uniform(0.5, 2.0)
        return img_pil.filter(ImageFilter.GaussianBlur(radius))

    return img_pil


# ==========================================
# 4. Main generation loop
# ==========================================
def generate_benign_augmentations():
    print(f"Starting CV-only Augmentation to: {Config.save_root}")
    print(f"Target count per brand: {Config.target_benign_count}")

    # Get all brand folders
    if not os.path.exists(Config.data_root):
        print(f"Error: Data root {Config.data_root} does not exist.")
        return

    for brand in tqdm(Config.brand_list, desc="Processing Brands"):
        src_brand_dir = os.path.join(Config.data_root, brand)
        dst_brand_dir = os.path.join(Config.save_root, brand)

        os.makedirs(dst_brand_dir, exist_ok=True)

        # Retrieve the original image (filtering out non-image files, page screenshots, and login screenshots).
        raw_images = [f for f in os.listdir(src_brand_dir) if f.lower().endswith(('.jpg', '.png', '.jpeg'))]
        if 'homepage.png' in raw_images:
            raw_images.remove('homepage.png')
        if 'loginpage.png' in raw_images:
            raw_images.remove('loginpage.png')

        if len(raw_images) == 0:
            continue

        # Calculate the number of copies needed to generate for each original image.
        # For example: Target 100 images, original 5 images -> Generate 20 images per image
        num_raw = len(raw_images)
        num_aug_per_img = math.ceil(Config.target_benign_count / num_raw)

        count = 0

        for img_name in raw_images:
            src_path = os.path.join(src_brand_dir, img_name)
            try:
                # 1. Open and perform basic preprocessing (convert to RGB, fill with a square, resize)
                img = Image.open(src_path).convert('RGB')
                img_base = square_pad_resize(img)

                # 2. Save a copy of the original preprocessed image (as a Seed)
                img_base.save(os.path.join(dst_brand_dir, f"original_{img_name}"))

                # 3. Looping to generate enhanced samples
                for i in range(num_aug_per_img):
                    if count >= Config.target_benign_count:
                        break

                    # Apply random enhancement
                    aug_img = apply_random_benign_aug(img_base)

                    save_name = f"aug_{i}_{img_name}"
                    aug_img.save(os.path.join(dst_brand_dir, save_name))

                    count += 1

            except Exception as e:
                print(f"Error processing {src_path}: {e}")


if __name__ == "__main__":
    generate_benign_augmentations()
    print(f"\n[Done] Dataset generation completed.")